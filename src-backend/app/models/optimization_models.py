from sqlalchemy import Column, String, Float, DateTime, ForeignKey, JSON, Text, Integer
from sqlalchemy.orm import relationship
from datetime import datetime, timezone
from app.models.base import Base
import uuid

def get_utc_now():
    return datetime.now(timezone.utc)

def generate_uuid():
    return str(uuid.uuid4())

class OptimizationStrategy(Base):
    """Registry of available optimization strategies (Green, Carbon, Economic)."""
    __tablename__ = "optimization_strategies"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    name = Column(String(100), nullable=False, unique=True)
    description = Column(String(255))
    created_at = Column(DateTime(timezone=True), default=get_utc_now)

class RecommendationRecord(Base):
    """Historical record of optimization recommendations generated by the engine."""
    __tablename__ = "optimization_recommendations"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    strategy_id = Column(String(36), ForeignKey("optimization_strategies.id"), nullable=False)
    generated_at = Column(DateTime(timezone=True), default=get_utc_now, nullable=False)
    
    # Impacts
    expected_savings = Column(Float, default=0.0)
    carbon_reduction = Column(Float, default=0.0)
    renewable_increase = Column(Float, default=0.0)
    confidence_score = Column(Float, nullable=False)
    
    # Payload of actual actions/setpoints recommended (JSON)
    recommendation_details = Column(JSON, nullable=False)
    
    # State tracking if the operator accepted it
    status = Column(String(50), default="pending") # pending, accepted, rejected
    
class ScenarioSimulation(Base):
    """User-triggered What-If scenarios."""
    __tablename__ = "optimization_scenarios"
    
    id = Column(String(36), primary_key=True, default=generate_uuid)
    name = Column(String(100), nullable=False)
    simulated_at = Column(DateTime(timezone=True), default=get_utc_now, nullable=False)
    
    # The overrides applied (e.g. +20% demand)
    overrides_json = Column(JSON, nullable=False)
    
    # The resulting best strategy
    recommended_strategy_id = Column(String(36), ForeignKey("optimization_strategies.id"), nullable=False)
    expected_savings = Column(Float, default=0.0)
    confidence_score = Column(Float, nullable=False)


class OptimizationConfig(Base):
    """Configuration settings for optimization algorithms and resource limits."""
    __tablename__ = "optimization_configs"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    name = Column(String(100), nullable=False)
    mode = Column(String(50), nullable=False, default="BALANCED") # BALANCED, ECONOMIC, GREEN, STABILITY
    solver_settings_json = Column(JSON, nullable=True) # max_iterations, tolerance, timeout
    resource_limits_json = Column(JSON, nullable=True) # cpu_cores, memory_mb
    constraints_json = Column(JSON, nullable=True) # enabled constraints list
    objectives_json = Column(JSON, nullable=True) # weights for objectives
    created_at = Column(DateTime(timezone=True), default=get_utc_now)


class OptimizationJob(Base):
    """Lifecycles of secure grid optimization task executions."""
    __tablename__ = "optimization_jobs"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    status = Column(String(20), default="PENDING", nullable=False) # PENDING, QUEUED, RUNNING, COMPLETED, FAILED, CANCELLED
    priority = Column(String(20), default="MEDIUM", nullable=False) # LOW, MEDIUM, HIGH, CRITICAL
    config_id = Column(String(36), ForeignKey("optimization_configs.id"), nullable=False)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=True) # Operator correlation context
    scheduled_at = Column(DateTime(timezone=True), default=get_utc_now, nullable=False)
    started_at = Column(DateTime(timezone=True), nullable=True)
    completed_at = Column(DateTime(timezone=True), nullable=True)
    progress = Column(Float, default=0.0, nullable=False) # 0.0 to 100.0
    error_message = Column(String(255), nullable=True)

    config = relationship("OptimizationConfig")
    user = relationship("User")


class OptimizationExecutionHistory(Base):
    """Post-execution log metrics and result payloads from optimization runs."""
    __tablename__ = "optimization_execution_history"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    job_id = Column(String(36), ForeignKey("optimization_jobs.id"), nullable=False)
    execution_time_ms = Column(Float, default=0.0, nullable=False)
    objective_score = Column(Float, default=0.0)
    results_json = Column(JSON, nullable=True)
    metrics_json = Column(JSON, nullable=True)
    logs = Column(Text, nullable=True)
    created_at = Column(DateTime(timezone=True), default=get_utc_now)

    job = relationship("OptimizationJob")


