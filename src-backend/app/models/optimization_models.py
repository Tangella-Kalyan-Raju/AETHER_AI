class OptimizationAnalyticsSnapshot(Base):
    """Periodic KPI snapshots aggregating optimization performance over time."""
    __tablename__ = "optimization_analytics_snapshots"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    period = Column(String(20), nullable=False)  # DAILY, WEEKLY, MONTHLY
    period_start = Column(DateTime(timezone=True), nullable=False)
    period_end = Column(DateTime(timezone=True), nullable=False)

    # Aggregate KPIs
    total_jobs = Column(Integer, default=0)
    successful_jobs = Column(Integer, default=0)
    failed_jobs = Column(Integer, default=0)
    cancelled_jobs = Column(Integer, default=0)
    success_rate = Column(Float, default=0.0)
    avg_execution_time_ms = Column(Float, default=0.0)
    avg_objective_score = Column(Float, default=0.0)

    # Financial & Environmental KPIs
    avg_cost_savings_usd = Column(Float, default=0.0)
    avg_carbon_avoided_tons = Column(Float, default=0.0)
    avg_stability_score = Column(Float, default=0.0)
    avg_renewable_pct = Column(Float, default=0.0)
    avg_ai_confidence = Column(Float, default=0.0)

    # Extended metrics JSON
    metrics_json = Column(JSON, nullable=True)
    created_at = Column(DateTime(timezone=True), default=get_utc_now)


class OptimizationAuditEntry(Base):
    """Immutable audit log per optimization job for governance and compliance."""
    __tablename__ = "optimization_audit_entries"

    id = Column(String(36), primary_key=True, default=generate_uuid)
    job_id = Column(String(36), ForeignKey("optimization_jobs.id"), nullable=False)
    user_id = Column(Integer, ForeignKey("users.id"), nullable=True)
    timestamp = Column(DateTime(timezone=True), default=get_utc_now, nullable=False)

    # Decision context
    config_mode = Column(String(50), nullable=True)
    objectives_json = Column(JSON, nullable=True)
    constraints_json = Column(JSON, nullable=True)
    strategy_selected = Column(String(100), nullable=True)
    alternative_strategies_json = Column(JSON, nullable=True)
    ai_recommendation_json = Column(JSON, nullable=True)
    confidence_score = Column(Float, default=0.0)

    # Execution context
    execution_time_ms = Column(Float, default=0.0)
    final_status = Column(String(20), nullable=True)
    objective_score = Column(Float, default=0.0)
    warnings_json = Column(JSON, nullable=True)
    errors_json = Column(JSON, nullable=True)

    job = relationship("OptimizationJob")
    user = relationship("User")


